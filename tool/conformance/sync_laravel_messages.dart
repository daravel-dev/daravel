import 'dart:convert';
import 'dart:io';

/// Regenerates the Laravel validation message fixture used by the
/// conformance suite:
///
/// ```bash
/// dart run tool/conformance/sync_laravel_messages.dart            # 12.x
/// dart run tool/conformance/sync_laravel_messages.dart path/to/validation.php
/// ```
///
/// Reads `src/Illuminate/Translation/lang/en/validation.php` from
/// laravel/framework (downloaded, or a local copy) and writes
/// `packages/daravel_test/lib/src/conformance/laravel_validation_messages.dart`.
/// Nested size rules become dotted keys (`min.string`), as in Daravel's
/// catalog. The `custom` and `attributes` sections are skipped.
Future<void> main(List<String> args) async {
  const branch = '12.x';
  const source =
      'https://raw.githubusercontent.com/laravel/framework/$branch/'
      'src/Illuminate/Translation/lang/en/validation.php';
  final php = args.isEmpty
      ? await _download(source)
      : File(args.first).readAsStringSync();
  final messages = parseValidationPhp(php);
  if (messages.length < 50) {
    stderr.writeln('Parsed only ${messages.length} messages; aborting.');
    exitCode = 1;
    return;
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/conformance/sync_laravel_messages.dart.')
    ..writeln('// Source: laravel/framework $branch,')
    ..writeln('// src/Illuminate/Translation/lang/en/validation.php.')
    ..writeln('// Copyright (c) Taylor Otwell, MIT License: see')
    ..writeln('// THIRD_PARTY_NOTICES.md.')
    ..writeln('// Do not edit by hand; rerun the tool instead.')
    ..writeln()
    ..writeln('/// Laravel $branch default English validation messages.')
    ..writeln('const Map<String, String> laravelValidationMessages = {');
  for (final entry in messages.entries) {
    out.writeln("  ${_dartString(entry.key)}: ${_dartString(entry.value)},");
  }
  out.writeln('};');
  final target = File(
    'packages/daravel_test/lib/src/conformance/laravel_validation_messages.dart',
  );
  target.parent.createSync(recursive: true);
  target.writeAsStringSync(out.toString());
  stdout.writeln('Wrote ${messages.length} messages to ${target.path}.');
}

/// Flattens the PHP array literal of `validation.php` into dotted keys.
Map<String, String> parseValidationPhp(String php) {
  final result = <String, String>{};
  final entry = RegExp(
    r"""'([A-Za-z0-9_.-]+)'\s*=>\s*(?:'((?:[^'\\]|\\.)*)'|\[)""",
  );
  String? parent;
  var depth = 0;
  var skipping = false;
  for (final raw in const LineSplitter().convert(php)) {
    final line = raw.trim();
    if (line.startsWith('//') ||
        line.startsWith('*') ||
        line.startsWith('/*')) {
      continue;
    }
    final match = entry.firstMatch(line);
    if (match != null) {
      final key = match.group(1)!;
      final value = match.group(2);
      if (value == null) {
        if (line.contains('[]')) {
          continue; // Empty array literal.
        }
        // Opening a nested array.
        depth++;
        if (depth == 1) {
          parent = key;
          skipping = key == 'custom' || key == 'attributes';
        }
        continue;
      }
      if (skipping) {
        continue;
      }
      final unescaped = value.replaceAll(r"\'", "'");
      result[depth >= 1 && parent != null ? '$parent.$key' : key] = unescaped;
      continue;
    }
    if (line.startsWith('],') || line == ']') {
      if (depth > 0) {
        depth--;
        if (depth == 0) {
          parent = null;
          skipping = false;
        }
      }
    }
  }
  return result;
}

String _dartString(String value) =>
    "'${value.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

Future<String> _download(String url) async {
  final client = HttpClient();
  try {
    final response = await (await client.getUrl(Uri.parse(url))).close();
    if (response.statusCode != 200) {
      throw HttpException('GET $url → ${response.statusCode}');
    }
    return await response.transform(utf8.decoder).join();
  } finally {
    client.close();
  }
}
