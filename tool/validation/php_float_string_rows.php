function bits(float $d): int
{
    return unpack('J', pack('E', $d))[1];
}

function fromBits(int $bits): float
{
    return unpack('E', pack('J', $bits))[1];
}

// 64 random bits (mt_rand gives 31 at a time).
function randomBits(): int
{
    return (mt_rand(0, 0xFFFF) << 48) | (mt_rand(0, 0xFFFFFF) << 24) | mt_rand(0, 0xFFFFFF);
}

// An integer of exactly $digits decimal digits.
function randomDigits(int $digits): int
{
    $n = mt_rand(1, 9);
    for ($i = 1; $i < $digits; $i++) {
        $n = $n * 10 + mt_rand(0, 9);
    }
    return $n;
}

$kinds = [];
function add(string $kind, float ...$values): void
{
    global $kinds;
    foreach ($values as $d) {
        $kinds[$kind][] = $d;
    }
}

// The double itself, the one below and the one above.
function addWithNeighbours(string $kind, float $d): void
{
    $b = bits($d);
    add($kind, $d, fromBits($b - 1), fromBits($b + 1));
}

