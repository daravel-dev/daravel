import 'dart:collection';

import 'package:daravel/daravel.dart';
import 'package:test/test.dart';

/// `distinct:strict` against Laravel 12.x `ValidatesAttributes::validateDistinct`
/// (`src/Illuminate/Validation/Concerns/ValidatesAttributes.php`):
///
/// ```php
/// return ! in_array($value, array_values($data), in_array('strict', $parameters));
/// ```
///
/// With `strict`, two values are duplicates only when PHP's `===` holds.
/// Any other parameter is ignored (`STRICT` is not `strict`); `ignore_case`
/// is covered by `distinct_ignore_case_test.dart`, and wins over `strict`.
void main() {
  // The values of the tables, in the order of the rows and columns.
  const labels = <String>[
    '1',
    '"1"',
    '1.0',
    'true',
    'false',
    'null',
    '0',
    '"0"',
    '-0.0',
    '"-0"',
    '""',
    '"a"',
    '"A"',
    '1000.0',
    '"1e3"',
    '0.30000000000000004',
    '"0.3"',
    '1e20',
    '9007199254740993',
    '9007199254740992',
    '9007199254740992.0',
    '[1, 2]',
    '["1", "2"]',
    '{"a": 1}',
  ];
  final values = <Object?>[
    1,
    '1',
    1.0,
    true,
    false,
    null,
    0,
    '0',
    -0.0,
    '-0',
    '',
    'a',
    'A',
    1000.0,
    '1e3',
    0.30000000000000004,
    '0.3',
    1e20,
    9007199254740993,
    9007199254740992,
    9007199254740992.0,
    [1, 2],
    ['1', '2'],
    {'a': 1},
  ];

  // PHP 8.4.28: row x, column y is `in_array($x, [$y], true)` for the
  // values above, in the same order, generated by running PHP over every
  // ordered pair. Only the diagonal holds: one value `===` only itself.
  const phpStrict = <String>[
    '100000000000000000000000',
    '010000000000000000000000',
    '001000000000000000000000',
    '000100000000000000000000',
    '000010000000000000000000',
    '000001000000000000000000',
    '000000100000000000000000',
    '000000010000000000000000',
    '000000001000000000000000',
    '000000000100000000000000',
    '000000000010000000000000',
    '000000000001000000000000',
    '000000000000100000000000',
    '000000000000010000000000',
    '000000000000001000000000',
    '000000000000000100000000',
    '000000000000000010000000',
    '000000000000000001000000',
    '000000000000000000100000',
    '000000000000000000010000',
    '000000000000000000001000',
    '000000000000000000000100',
    '000000000000000000000010',
    '000000000000000000000001',
  ];

  // Plain `distinct`, unchanged from 1.27.7: the values' text is compared,
  // so `1` equals `"1"`, `0` equals `"0"`, and `[1, 2]` equals `["1", "2"]`
  // (both read `[1, 2]`). Observed by running the rule of 1.27.7 over every
  // ordered pair; the row of `""` is empty because the validator skips an
  // empty string.
  const plainObserved = <String>[
    '110000000000000000000000',
    '110000000000000000000000',
    '001000000000000000000000',
    '000100000000000000000000',
    '000010000000000000000000',
    '000001000000000000000000',
    '000000110000000000000000',
    '000000110000000000000000',
    '000000001000000000000000',
    '000000000100000000000000',
    '000000000000000000000000',
    '000000000001000000000000',
    '000000000000100000000000',
    '000000000000010000000000',
    '000000000000001000000000',
    '000000000000000100000000',
    '000000000000000010000000',
    '000000000000000001000000',
    '000000000000000000100000',
    '000000000000000000010000',
    '000000000000000000001000',
    '000000000000000000000110',
    '000000000000000000000110',
    '000000000000000000000001',
  ];

  Future<Set<String>> failing(Object rule, List<Object?> items) async =>
      (await Validator({'items': items}, {'items.*': rule}).run()).keys.toSet();

  test(
    'distinct:strict: every ordered pair agrees with PHP in_array(===)',
    () async {
      expect(phpStrict.length, values.length);
      for (var x = 0; x < values.length; x++) {
        for (var y = 0; y < values.length; y++) {
          var expected = phpStrict[x][y] == '1';
          // The validator does not run a rule on an empty string: `""`
          // beside `""` passes where PHP's `===` is true. Beside anything
          // else it is a different value, as in PHP. (`null` does run.)
          if (values[x] == '') {
            expected = false;
          }
          final errors = await failing('distinct:strict', [
            values[x],
            values[y],
          ]);
          expect(
            errors.contains('items.0'),
            expected,
            reason: '${labels[x]} beside ${labels[y]}',
          );
        }
      }
    },
  );

  test('plain distinct is unchanged from 1.27.7 (text comparison)', () async {
    for (var x = 0; x < values.length; x++) {
      for (var y = 0; y < values.length; y++) {
        final errors = await failing('distinct', [values[x], values[y]]);
        expect(
          errors.contains('items.0'),
          plainObserved[x][y] == '1',
          reason: '${labels[x]} beside ${labels[y]}',
        );
      }
    }
  });

  test(
    'strict: NaN is never equal, not even to itself; -0.0 equals 0.0',
    () async {
      const nan = double.nan;
      expect(await failing('distinct:strict', [nan, nan]), isEmpty);
      expect(await failing('distinct:strict', [nan, nan, 1]), isEmpty);
      expect(
        await failing('distinct:strict', [
          [nan],
          [nan],
        ]),
        isEmpty,
      );
      expect(await failing('distinct:strict', [-0.0, 0.0]), {
        'items.0',
        'items.1',
      });
      expect(await failing('distinct:strict', [0.0, -0.0]), {
        'items.0',
        'items.1',
      });
    },
  );

  test('strict: a list equals a map of the keys 0..n-1, in order', () async {
    expect(
      await failing('distinct:strict', [
        ['a', 'b'],
        {'0': 'a', '1': 'b'},
      ]),
      {'items.0', 'items.1'},
    );
    expect(
      await failing('distinct:strict', [
        ['a', 'b'],
        {'1': 'b', '0': 'a'},
      ]),
      isEmpty,
    );
    expect(
      await failing('distinct:strict', [
        ['a', 'b'],
        ['b', 'a'],
      ]),
      isEmpty,
    );
    expect(
      await failing('distinct:strict', [
        {'a': 1, 'b': 2},
        {'a': 1, 'b': 2},
      ]),
      {'items.0', 'items.1'},
    );
    expect(
      await failing('distinct:strict', [
        {'a': 1},
        {'a': '1'},
      ]),
      isEmpty,
    );
    expect(
      await failing('distinct:strict', [
        [
          1,
          [2, '3'],
        ],
        [
          1,
          [2, '3'],
        ],
      ]),
      {'items.0', 'items.1'},
    );
    // A string that looks like another value's encoding is still a string.
    expect(await failing('distinct:strict', ['s1:a', 'a']), isEmpty);
    expect(
      await failing('distinct:strict', [
        ['a', 'b'],
        ['a', 'b', ''],
      ]),
      isEmpty,
    );
  });

  group('objects equal only themselves, at any depth', () {
    UploadedFile file() => UploadedFile.fake.withContent('a.txt', 'x');

    test('top level', () async {
      expect(await failing('distinct:strict', [file(), file()]), isEmpty);
      final same = file();
      expect(await failing('distinct:strict', [same, same]), {
        'items.0',
        'items.1',
      });
    });

    test('in a map under a wildcard field', () async {
      Future<Set<String>> run(List<Object?> items) async => (await Validator(
        {'items': items},
        {'items.*.file': 'distinct:strict'},
      ).run()).keys.toSet();
      expect(
        await run([
          {'file': file()},
          {'file': file()},
        ]),
        isEmpty,
      );
      final same = file();
      expect(
        await run([
          {'file': same},
          {'file': same},
        ]),
        {'items.0.file', 'items.1.file'},
      );
    });

    test('inside the compared maps and lists', () async {
      expect(
        await failing('distinct:strict', [
          {'file': file()},
          {'file': file()},
        ]),
        isEmpty,
      );
      expect(
        await failing('distinct:strict', [
          [file()],
          [file()],
        ]),
        isEmpty,
      );
      final same = file();
      expect(
        await failing('distinct:strict', [
          {'file': same},
          {'file': same},
        ]),
        {'items.0', 'items.1'},
      );
      expect(
        await failing('distinct:strict', [
          [same],
          [same],
        ]),
        {'items.0', 'items.1'},
      );
      expect(
        await failing('distinct:strict', [
          [
            {'f': same},
          ],
          [
            {'f': file()},
          ],
        ]),
        isEmpty,
      );
    });

    test('records are never equal', () async {
      expect(await failing('distinct:strict', [(1, 2), (1, 2)]), isEmpty);
    });
  });

  group('parameters', () {
    Future<bool> strict(Object rule) async =>
        (await failing(rule, [1, '1'])).isEmpty;

    test('strict in any position, trimmed, is strict', () async {
      for (final rule in [
        'distinct:strict',
        'distinct:x,strict',
        'distinct: strict',
        'distinct:strict,x',
        Rules.distinct(strict: true),
      ]) {
        expect(await strict(rule), isTrue, reason: '$rule');
      }
    });

    test('other forms are plain distinct', () async {
      for (final rule in [
        'distinct',
        'distinct:STRICT',
        'distinct:ignore_case',
        'distinct:foo',
        Rules.distinct(),
      ]) {
        expect(await strict(rule), isFalse, reason: '$rule');
      }
    });

    test('Rules.distinct(strict: true) is the string form', () async {
      expect(const DistinctRule(strict: true).strict, isTrue);
      expect(const DistinctRule().strict, isFalse);
      for (final items in <List<Object?>>[
        [1, '1', 1, 1.0],
        ['a', 'a'],
        [1, 2, 3],
      ]) {
        expect(
          await failing(Rules.distinct(strict: true), items),
          await failing('distinct:strict', items),
        );
      }
    });
  });

  group('grouping is the one of plain distinct', () {
    Future<Set<String>> run(Map<String, Object?> data, String pattern) async =>
        (await Validator(data, {
          pattern: 'distinct:strict',
        }).run()).keys.toSet();

    test('values are compared strictly within a parent', () async {
      expect(
        await run({
          'a': [
            {
              'items': [
                {'id': 1},
                {'id': '1'},
              ],
            },
          ],
        }, 'a.*.items.*.id'),
        isEmpty,
      );
    });

    test('two wildcards compare within their parent', () async {
      Map<String, Object?> parent(List<Object?> ids) => {
        'items': [
          for (final id in ids) {'id': id},
        ],
      };
      expect(
        await run({
          'a': [
            parent([1]),
            parent([1]),
          ],
        }, 'a.*.items.*.id'),
        isEmpty,
      );
      expect(
        await run({
          'a': [
            parent([1, 1]),
            parent([1]),
          ],
        }, 'a.*.items.*.id'),
        {'a.0.items.0.id', 'a.0.items.1.id'},
      );
    });

    test('an empty key is compared, not counted', () async {
      expect(
        await run({
          'items': {
            '': {'id': 1},
            'x': {'id': 1},
          },
        }, 'items.*.id'),
        {'items..id'},
      );
      expect(
        await run({
          '': {
            '': ['dup', 'dup'],
          },
        }, '*.*.*'),
        isEmpty,
      );
    });

    test('an item without the field is not compared', () async {
      expect(
        await run({
          'items': [
            <String, Object?>{},
            <String, Object?>{},
            {'id': 'null'},
          ],
        }, 'items.*.id'),
        isEmpty,
      );
    });

    test('a JSON object, and a one-star pattern over all items', () async {
      expect(
        await run({
          'items': {
            'a': {'id': 1},
            'b': {'id': 1},
          },
        }, 'items.*.id'),
        {'items.a.id', 'items.b.id'},
      );
      expect(
        await run({
          'a': {
            'k': ['dup', 'dup'],
          },
        }, 'a.*.*'),
        {'a.k.0', 'a.k.1'},
      );
    });
  });

  group('deep and self-containing values', () {
    const limit = DistinctRule.distinctKeyDepth;
    final both = {'items.0', 'items.1'};

    // [depth] lists, one in the other, the innermost holding [leaf]: the
    // outermost (the compared value) is at depth 1, the innermost at
    // [depth]. Built with a loop, not recursion.
    List<Object?> nestedList(int depth, [Object? leaf = 1]) {
      var value = <Object?>[leaf];
      for (var i = 1; i < depth; i++) {
        value = <Object?>[value];
      }
      return value;
    }

    Map<String, Object?> nestedMap(int depth) {
      var value = <String, Object?>{'v': 1};
      for (var i = 1; i < depth; i++) {
        value = <String, Object?>{'v': value};
      }
      return value;
    }

    List<Object?> selfList() {
      final list = <Object?>[1];
      list.add(list);
      return list;
    }

    Map<String, Object?> selfMap() {
      final map = <String, Object?>{'v': 1};
      map['m'] = map;
      return map;
    }

    // a contains b, b contains a.
    List<Object?> twoCycle() {
      final a = <Object?>['a'];
      final b = <Object?>['b', a];
      a.add(b);
      return a;
    }

    // [depth] maps, one in the other; the innermost has a list as its key,
    // which sits one level deeper than that map.
    Map<Object?, Object?> listKeyedMap(int depth) {
      var value = <Object?, Object?>{
        <Object?>[1]: 'v',
      };
      for (var i = 1; i < depth; i++) {
        value = <Object?, Object?>{'v': value};
      }
      return value;
    }

    test('a list or map used as a map key counts one level deeper than its '
        'map', () async {
      // The key is at the limit: compared by content.
      expect(
        await failing('distinct:strict', [
          listKeyedMap(limit - 1),
          listKeyedMap(limit - 1),
        ]),
        both,
      );
      // One level deeper: each key equals only itself.
      expect(
        await failing('distinct:strict', [
          listKeyedMap(limit),
          listKeyedMap(limit),
        ]),
        isEmpty,
      );
    });

    test('a list that validates something else while it is read keeps its '
        'own walk', () async {
      // The path of a walk belongs to that walk: another comparison started
      // from inside an element read must not make the outer one forget
      // where it is.
      final list = _ValidatingSelfList();
      expect(await failing('distinct:strict', [list, list]), both);
      expect(list.reads, lessThan(20), reason: 'walked into itself');
    });

    test('20 000 levels: no error, equal only to itself', () async {
      expect(
        await failing('distinct:strict', [
          nestedList(20000),
          nestedList(20000),
        ]),
        isEmpty,
      );
      expect(
        await failing('distinct:strict', [nestedMap(20000), nestedMap(20000)]),
        isEmpty,
      );
      final same = nestedList(20000);
      expect(await failing('distinct:strict', [same, same]), both);
    });

    test(
      'a container at the limit is compared, one level deeper not',
      () async {
        expect(
          await failing('distinct:strict', [
            nestedList(limit),
            nestedList(limit),
          ]),
          both,
        );
        expect(
          await failing('distinct:strict', [
            nestedList(limit + 1),
            nestedList(limit + 1),
          ]),
          isEmpty,
        );
        expect(
          await failing('distinct:strict', [
            nestedMap(limit),
            nestedMap(limit),
          ]),
          both,
        );
        expect(
          await failing('distinct:strict', [
            nestedMap(limit + 1),
            nestedMap(limit + 1),
          ]),
          isEmpty,
        );
        // At the limit the content still decides.
        expect(
          await failing('distinct:strict', [
            nestedList(limit),
            nestedList(limit, 2),
          ]),
          isEmpty,
        );
      },
    );

    test('a list or map that contains itself', () async {
      expect(
        await failing('distinct:strict', [selfList(), selfList()]),
        isEmpty,
      );
      final list = selfList();
      expect(await failing('distinct:strict', [list, list]), both);
      expect(await failing('distinct:strict', [selfMap(), selfMap()]), isEmpty);
      final map = selfMap();
      expect(await failing('distinct:strict', [map, map]), both);
    });

    test('a list that contains itself twice is not walked again', () async {
      // Walked again at every level, it would take 2^512 steps.
      List<Object?> wide() {
        final list = <Object?>[];
        list
          ..add(list)
          ..add(list);
        return list;
      }

      expect(await failing('distinct:strict', [wide(), wide()]), isEmpty);
      final same = wide();
      expect(await failing('distinct:strict', [same, same]), both);
    }, timeout: const Timeout(Duration(seconds: 20)));

    test('a cycle through two lists', () async {
      expect(
        await failing('distinct:strict', [twoCycle(), twoCycle()]),
        isEmpty,
      );
      final a = twoCycle();
      expect(await failing('distinct:strict', [a, a]), both);
    });

    test('a list or map met twice side by side is not a cycle', () async {
      final shared = <Object?>[
        1,
        <Object?>['x'],
      ];
      expect(
        await failing('distinct:strict', [
          [shared, shared],
          [
            [
              1,
              ['x'],
            ],
            [
              1,
              ['x'],
            ],
          ],
        ]),
        both,
      );
      final sharedMap = <String, Object?>{'k': 1};
      expect(
        await failing('distinct:strict', [
          {'a': sharedMap, 'b': sharedMap},
          {
            'a': {'k': 1},
            'b': {'k': 1},
          },
        ]),
        both,
      );
    });

    test('ignore_case: deep and self-containing values', () async {
      expect(
        await failing('distinct:ignore_case', [
          nestedList(20000),
          nestedList(20000),
        ]),
        isEmpty,
      );
      expect(
        await failing('distinct:ignore_case', [selfList(), selfList()]),
        isEmpty,
      );
      expect(
        await failing('distinct:ignore_case', [selfMap(), selfMap()]),
        isEmpty,
      );
      final list = selfList();
      expect(await failing('distinct:ignore_case', [list, list]), both);
      final map = selfMap();
      expect(await failing('distinct:ignore_case', [map, map]), both);
      expect(
        await failing('distinct:ignore_case', [
          nestedList(limit),
          nestedList(limit),
        ]),
        both,
      );
    });

    test('ordinary values keep their keys', () async {
      expect(await failing('distinct:strict', [1, '1']), isEmpty);
      expect(await failing('distinct:strict', [1, 1.0]), isEmpty);
      expect(await failing('distinct:strict', ['a', 'a']), both);
      expect(await failing('distinct:strict', [-0.0, 0.0]), both);
      expect(
        await failing('distinct:strict', [double.nan, double.nan]),
        isEmpty,
      );
      expect(
        await failing('distinct:strict', [
          ['a', 'b'],
          {'0': 'a', '1': 'b'},
        ]),
        both,
      );
      expect(
        await failing('distinct:strict', [
          ['a', 'b'],
          {'1': 'b', '0': 'a'},
        ]),
        isEmpty,
      );
      expect(
        await failing('distinct:strict', [
          {'a': 1},
          {'a': '1'},
        ]),
        isEmpty,
      );
      expect(
        await failing('distinct:strict', [
          [
            1,
            [2, '3'],
          ],
          [
            1,
            [2, '3'],
          ],
        ]),
        both,
      );
      expect(await failing('distinct:ignore_case', ['a', 'A']), both);
    });
  });

  group('the work is linear', () {
    Future<int> micros(List<Object?> items) async {
      final watch = Stopwatch()..start();
      final errors = await Validator(
        {'items': items},
        {'items.*': 'distinct:strict'},
      ).run();
      watch.stop();
      expect(errors, isEmpty);
      return watch.elapsedMicroseconds;
    }

    Future<int> best(List<Object?> items) async {
      var least = await micros(items);
      // A first run warms the code up; the best of five keeps a pause of
      // the machine out of the ratio.
      for (var i = 0; i < 4; i++) {
        final next = await micros(items);
        least = next < least ? next : least;
      }
      return least;
    }

    // Eight times the items: linear work is 8 times, quadratic 64. With
    // four times and a bound of 10 (against 16), a busy Windows runner once
    // measured 11.2 for linear work; 24 against 64 leaves room for that.
    test('distinct integers', () async {
      final small = await best([for (var i = 0; i < 5000; i++) i]);
      final large = await best([for (var i = 0; i < 40000; i++) i]);
      expect(large, lessThan(24 * small), reason: '$small us -> $large us');
    });

    test('distinct strings of 200 characters', () async {
      List<Object?> strings(int n) => [
        for (var i = 0; i < n; i++)
          '${'x' * 195}${i.toString().padLeft(5, '0')}',
      ];
      final small = await best(strings(5000));
      final large = await best(strings(40000));
      expect(large, lessThan(24 * small), reason: '$small us -> $large us');
    });
  });
}

/// A list of two elements, the second being the list itself, whose first
/// read runs another `distinct:strict` validation before it answers.
final class _ValidatingSelfList extends ListBase<Object?> {
  int reads = 0;
  bool _ran = false;

  @override
  int get length => 2;

  @override
  set length(int _) => throw UnsupportedError('fixed');

  @override
  Object? operator [](int index) {
    reads++;
    if (index == 0 && !_ran) {
      _ran = true;
      // Runs up to its first await at once, which is past the comparison.
      Validator(
        {
          'inner': [
            <Object?>[1],
            <Object?>[2],
          ],
        },
        {'inner.*': 'distinct:strict'},
      ).run().ignore();
    }
    return index == 0 ? 'first' : this;
  }

  @override
  void operator []=(int index, Object? value) =>
      throw UnsupportedError('fixed');
}
