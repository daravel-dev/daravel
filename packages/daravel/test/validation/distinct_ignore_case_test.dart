  group('the work is linear', () {
    Future<int> micros(
      List<Object?> items, [
      String rule = 'distinct:ignore_case',
    ]) async {
      var best = 1 << 62;
      // A first run warms the code up; the best of five keeps a pause of
      // the machine out of the ratio.
      await Validator({'items': items}, {'items.*': rule}).run();
      for (var run = 0; run < 5; run++) {
        final watch = Stopwatch()..start();
        await Validator({'items': items}, {'items.*': rule}).run();
        final elapsed = watch.elapsedMicroseconds;
        if (elapsed < best) {
          best = elapsed;
        }
      }
      return best;
    }

    final zhe = String.fromCharCode(0x416);
    final ya = String.fromCharCode(0x42F);
    final shapes = <String, Object? Function(int)>{
      'ASCII strings of 200 chars': (i) =>
          'Ab${'x' * 150}$i'.padRight(200, 'Z'),
      'non-ASCII strings of 200 chars': (i) =>
          '$eAcuteUpper${zhe * 150}$i'.padRight(200, ya),
      'lone-surrogate strings': (i) => '${'a' * 100}$lone$i',
      'doubles': (i) => i * 0.37 + 1e-3,
    };
    for (final MapEntry(:key, :value) in shapes.entries) {
      test(
        '$key: four times the items take less than 10 times as long',
        () async {
          final small = await micros([
            for (var i = 0; i < 10000; i++) value(i),
          ]);
          final large = await micros([
            for (var i = 0; i < 40000; i++) value(i),
          ]);
          // ignore: avoid_print
          print('$key: 10000 in ${small}us, 40000 in ${large}us');
          // Linear work is 4 times, quadratic 16.
          expect(large, lessThan(10 * small), reason: '$small -> $large');
        },
      );
    }

    test('non-ASCII text costs less than 25 times plain distinct', () async {
      final items = [
        for (var i = 0; i < 8000; i++)
          '$i${zhe * 497}$eAcuteUpper${ya * 497}'.padRight(1000, ya),
      ];
      // The two are measured in turns, so a busy stretch of the machine
      // falls on both. The ratio is about 4 on a quiet machine and was 9.6
      // once on a Windows CI runner with other test files running beside
      // it: the bound is for folding that got an order of magnitude
      // slower, not for a few percent.
      var plain = 1 << 62;
      var folded = 1 << 62;
      for (var turn = 0; turn < 3; turn++) {
        final p = await micros(items, 'distinct');
        final f = await micros(items);
        plain = p < plain ? p : plain;
        folded = f < folded ? f : folded;
      }
      // ignore: avoid_print
      print('8000 x 1000 chars: plain ${plain}us, ignore_case ${folded}us');
      expect(folded, lessThan(25 * plain), reason: '$plain vs $folded');
    });
  });
