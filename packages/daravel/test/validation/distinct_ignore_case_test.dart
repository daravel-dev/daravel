  group('every ordered pair agrees with PHP', () {
    Future<void> check(Object rule) async {
      expect(phpIgnoreCase.length, values.length);
      for (var x = 0; x < values.length; x++) {
        expect(phpIgnoreCase[x].length, values.length);
        for (var y = 0; y < values.length; y++) {
          var expected = phpIgnoreCase[x][y] == '1';
          // The validator does not run a rule on an empty string: the first
          // item then has no error, where PHP compares `""`. (`null` and
          // `false` run, and are `""` to PHP: they equal `""`, `null` and
          // `false`.)
          if (values[x] == '') {
            expected = false;
          }
          final errors = await failing(rule, [values[x], values[y]]);
          expect(
            errors.contains('items.0'),
            expected,
            reason: '${labels[x]} beside ${labels[y]} under $rule',
          );
        }
      }
    }

