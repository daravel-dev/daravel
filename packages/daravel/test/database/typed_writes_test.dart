import 'package:daravel/daravel.dart';
import 'package:test/test.dart';

/// The write methods `model:sync` generates (W9.13), as it writes them for
/// this table (`dartisan_cli/test/typed_writes_sync_test.dart` checks the
/// generator; this checks what the code does): every value sent reaches the
/// row (`fill` never drops one), `Patch(null)` writes NULL and
/// `Patch.absent()` leaves the column.
final class Member extends Model {
  static final ModelDefinition<Member> definition = ModelDefinition<Member>(
    table: 'members',
    factory: Member.new,
    fillable: ['name', 'nickname', 'verified_at'],
  );

  @override
  ModelDefinition<Member> get modelDefinition => Member.definition;

  // Generated by model:sync (accessors region), verbatim.
  /// Creates and saves a `Member` (`create` with a map, checked by
  static Future<Member> createWith({
    required String name,
    String? nickname,
    String? verifiedAt,
  }) => definition.query().create(<String, Object?>{
    'name': name,
    'nickname': ?nickname,
    'verified_at': ?verifiedAt,
  });

  /// [createWith] without saving (`make`).
  static Member makeWith({
    required String name,
    String? nickname,
    String? verifiedAt,
  }) => definition.query().make(<String, Object?>{
    'name': name,
    'nickname': ?nickname,
    'verified_at': ?verifiedAt,
  });

  /// Fills the given columns (`fill`); `Patch(null)` sets a nullable
  /// one to null.
  Member fillWith({
    String? name,
    Patch<String?> nickname = const Patch.absent(),
    Patch<String?> verifiedAt = const Patch.absent(),
  }) {
    fill(<String, Object?>{
      'name': ?name,
      if (nickname.isPresent) 'nickname': nickname.value,
      if (verifiedAt.isPresent) 'verified_at': verifiedAt.value,
    });
    return this;
  }

  /// Updates the given columns and saves (`update`); `Patch(null)` sets a
  /// nullable one to null.
  Future<bool> updateWith({
    String? name,
    Patch<String?> nickname = const Patch.absent(),
    Patch<String?> verifiedAt = const Patch.absent(),
  }) => update(<String, Object?>{
    'name': ?name,
    if (nickname.isPresent) 'nickname': nickname.value,
    if (verifiedAt.isPresent) 'verified_at': verifiedAt.value,
  });
}

void main() {
  late DatabaseManager db;
  late Container container;

  setUp(() async {
    db = DatabaseManager(
      const DatabaseConfig(
        defaultConnection: 'sqlite',
        connections: {
          'sqlite': ConnectionConfig(driver: 'sqlite', database: ':memory:'),
        },
      ),
    );
    await db.statement(
      'CREATE TABLE members ("id" INTEGER PRIMARY KEY AUTOINCREMENT, '
      '"name" TEXT NOT NULL, "nickname" TEXT, "verified_at" TEXT, '
      '"is_admin" INTEGER, "created_at" TEXT, "updated_at" TEXT)',
    );
    container = Container()..instance<DatabaseManager>(db);
  });

  tearDown(() => db.closeAll());

  Future<Map<String, Object?>> row() async =>
      (await db.table('members').first())!;

  test('createWith saves every value it is given', () async {
    await container.runScoped<void>('request', (_) async {
      await Member.createWith(
        name: 'Ana',
        nickname: 'an',
        verifiedAt: '2026-01-01 00:00:00',
      );
    });
    expect(await row(), containsPair('name', 'Ana'));
    expect(await row(), containsPair('nickname', 'an'));
    expect(await row(), containsPair('verified_at', '2026-01-01 00:00:00'));
  });

  test(
    'updateWith: Patch(null) writes NULL, absent leaves the column',
    () async {
      await container.runScoped<void>('request', (_) async {
        final member = await Member.createWith(name: 'Ana', nickname: 'an');
        await member.updateWith(name: 'Bea');
        expect(await row(), containsPair('nickname', 'an'));
        await member.updateWith(nickname: const Patch(null));
        expect(await row(), containsPair('nickname', null));
        expect(await row(), containsPair('name', 'Bea'));
      });
    },
  );

  test(
    'makeWith does not save; fillWith fills and returns the model',
    () async {
      await container.runScoped<void>('request', (_) async {
        final member = Member.makeWith(name: 'Ana');
        expect(member.exists, isFalse);
        expect(member.fillWith(nickname: const Patch('x')), same(member));
        expect(member.getAttr<String?>('nickname'), 'x');
        await member.save();
      });
      expect(await row(), containsPair('nickname', 'x'));
    },
  );
}
