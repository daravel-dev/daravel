import '../query_executor.dart';
import 'blueprint.dart';

/// SQLite DDL grammar.
final class SqliteSchemaGrammar extends SchemaGrammar {
  const SqliteSchemaGrammar();

  @override
  SqlDialect get dialect => SqlDialect.sqlite;

  @override
  String get autoIncrementClause => ' PRIMARY KEY AUTOINCREMENT NOT NULL';

  @override
  String typeFor(ColumnDefinition column) => switch (column.type) {
    .increments => 'INTEGER',
    .string => 'VARCHAR(${column.length ?? 255})',
    .char => 'VARCHAR(${column.length ?? 255})',
    .text || .mediumText || .longText => 'TEXT',
    .integer || .tinyInteger || .smallInteger || .bigInteger => 'INTEGER',
    .decimal => 'NUMERIC(${column.precision ?? 8}, ${column.scale ?? 2})',
    .float => 'FLOAT',
    .doublePrecision => 'DOUBLE',
    .boolean => 'TINYINT(1)',
    .date => 'DATE',
    .dateTime || ColumnType.timestamp => 'DATETIME',
    .time => 'TIME',
    .json => 'TEXT',
    .uuid => 'VARCHAR(36)',
    .binary => 'BLOB',
    .enumeration => 'VARCHAR(255)',
  };

  @override
  String compileTableExists() =>
      "SELECT name FROM sqlite_master WHERE type = 'table' AND name = ?";

  @override
  String compileListTables() =>
      "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'";

  @override
  String compileColumns() => 'PRAGMA table_info(?)';

  @override
  ColumnInfo columnInfo(Map<String, Object?> row) => ColumnInfo(
    name: row['name'] as String,
    type: row['type'] as String,
    nullable: row['notnull'] == 0,
    defaultValue: row['dflt_value'] as String?,
    primary: row['pk'] != 0,
    autoIncrement: row['autoincrement'] == true,
  );

  @override
  String compileDropForeign(String table, String name) =>
      throw UnsupportedError(
        'SQLite drops foreign keys by rebuilding the table.',
      );

  @override
  List<String> compileChange(String table, ColumnDefinition column) =>
      throw UnsupportedError('SQLite changes columns by rebuilding the table.');

  /// Whether [blueprint] needs the table-rebuild path on this SQLite version.
  bool requiresRebuild(Blueprint blueprint, SqliteVersion version) {
    if (blueprint.changedColumns.isNotEmpty ||
        blueprint.foreignKeys.isNotEmpty ||
        blueprint.dropForeignKeys.isNotEmpty) {
      return true;
    }
    if (blueprint.addedColumns.any(
      (c) => c.isUnique || c.isPrimary || c.isAutoIncrement,
    )) {
      return true;
    }
    if (blueprint.dropColumns.isNotEmpty && !version.atLeast(3, 35)) {
      return true;
    }
    if (blueprint.renameColumns.isNotEmpty && !version.atLeast(3, 25)) {
      return true;
    }
    return false;
  }
}

/// Parsed `sqlite_version()`.
final class SqliteVersion {
  const SqliteVersion(this.major, this.minor, this.patch);

  factory SqliteVersion.parse(String text) {
    final parts = text.split('.').map((p) => int.tryParse(p) ?? 0).toList();
    return SqliteVersion(
      parts.isNotEmpty ? parts[0] : 0,
      parts.length > 1 ? parts[1] : 0,
      parts.length > 2 ? parts[2] : 0,
    );
  }

  final int major;
  final int minor;
  final int patch;

  bool atLeast(int major, int minor) =>
      this.major > major || (this.major == major && this.minor >= minor);

  @override
  String toString() => '$major.$minor.$patch';
}

final class _ExistingColumn {
  _ExistingColumn({
    required this.name,
    required this.type,
    required this.notNull,
    required this.defaultSql,
    required this.primaryKey,
    required this.autoIncrement,
  });

  String name;
  String type;
  bool notNull;
  String? defaultSql;
  bool primaryKey;
  bool autoIncrement;
}

final class _ExistingIndex {
  _ExistingIndex({
    required this.name,
    required this.unique,
    required this.columns,
    required this.auto,
  });

  String name;
  final bool unique;
  final List<String> columns;

  /// Auto-generated by a UNIQUE/PRIMARY constraint (not a CREATE INDEX).
  final bool auto;
}

final class _ExistingForeignKey {
  _ExistingForeignKey({
    required this.table,
    required this.from,
    required this.to,
    required this.onDelete,
    required this.onUpdate,
  });

  String table;
  final List<String> from;
  final List<String> to;
  final String onDelete;
  final String onUpdate;
}

/// Rebuilds a SQLite table to apply changes `ALTER TABLE` cannot express
/// (the documented 12-step procedure, as Laravel/Doctrine do):
/// create a temp table with the new definition, copy rows, drop the old
/// table, rename, recreate indexes. Works inside the migration transaction
/// because the old table is dropped only after the rebuilt table has taken
/// its name.
final class SqliteTableRebuilder {
  SqliteTableRebuilder(this._executor, {SqliteSchemaGrammar? grammar})
    : grammar = grammar ?? const SqliteSchemaGrammar();

  final QueryExecutor _executor;
  final SqliteSchemaGrammar grammar;

  Future<void> rebuild(Blueprint blueprint) async {
    final table = blueprint.table;
    final columns = await _columns(table);
    final indexes = await _indexes(table);
    final foreignKeys = await _foreignKeys(table);
    final selectSources = <String, String>{
      for (final c in columns) c.name: c.name,
    };

    // Renames.
    for (final (from, to) in blueprint.renameColumns) {
      final column = columns.firstWhere(
        (c) => c.name == from,
        orElse: () =>
            throw StateError('Column [$from] does not exist on [$table].'),
      );
      column.name = to;
      selectSources[to] = selectSources.remove(from)!;
      for (final index in indexes) {
        _replace(index.columns, from, to);
      }
      for (final key in foreignKeys) {
        _replace(key.from, from, to);
      }
    }
    // Drops.
    for (final name in blueprint.dropColumns) {
      columns.removeWhere((c) => c.name == name);
      selectSources.remove(name);
      indexes.removeWhere((i) => i.columns.contains(name));
      foreignKeys.removeWhere((k) => k.from.contains(name));
    }
    // Changes.
    for (final change in blueprint.changedColumns) {
      final index = columns.indexWhere((c) => c.name == change.name);
      if (index == -1) {
        throw StateError('Column [${change.name}] does not exist on [$table].');
      }
      columns[index] = _fromDefinition(change);
      if (change.isUnique &&
          !indexes.any(
            (i) =>
                i.unique &&
                i.columns.length == 1 &&
                i.columns.first == change.name,
          )) {
        indexes.add(
          _ExistingIndex(
            name: '${table}_${change.name}_unique',
            unique: true,
            columns: [change.name],
            auto: false,
          ),
        );
      }
    }
    // Additions.
    for (final added in blueprint.addedColumns) {
      columns.add(_fromDefinition(added));
      if (added.isUnique) {
        indexes.add(
          _ExistingIndex(
            name: '${table}_${added.name}_unique',
            unique: true,
            columns: [added.name],
            auto: false,
          ),
        );
      }
      if (added.hasIndex) {
        indexes.add(
          _ExistingIndex(
            name: '${table}_${added.name}_index',
            unique: false,
            columns: [added.name],
            auto: false,
          ),
        );
      }
    }
    for (final index in blueprint.indexes) {
      indexes.add(
        _ExistingIndex(
          name: index.nameFor(table),
          unique: index.unique,
          columns: index.columns,
          auto: false,
        ),
      );
    }
    for (final name in blueprint.dropIndexes) {
      indexes.removeWhere((i) => i.name == name);
    }
    // Foreign keys.
    for (final name in blueprint.dropForeignKeys) {
      foreignKeys.removeWhere(
        (k) => '${table}_${k.from.join('_')}_foreign' == name,
      );
    }
    for (final key in blueprint.foreignKeys) {
      foreignKeys.add(
        _ExistingForeignKey(
          table:
              key.referencedTable ??
              (throw StateError('Foreign key is missing .on(table).')),
          from: key.columns,
          to: key.referencedColumns,
          onDelete: key.onDeleteAction ?? 'NO ACTION',
          onUpdate: key.onUpdateAction ?? 'NO ACTION',
        ),
      );
    }

    final definition = <String>[
      for (final column in columns) _compileExisting(column),
      for (final index in indexes.where((i) => i.auto && i.unique))
        'UNIQUE (${index.columns.map(grammar.wrap).join(', ')})',
      for (final key in foreignKeys)
        'FOREIGN KEY (${key.from.map(grammar.wrap).join(', ')}) REFERENCES ${grammar.wrap(key.table)} '
            '(${key.to.map(grammar.wrap).join(', ')}) ON DELETE ${key.onDelete} ON UPDATE ${key.onUpdate}',
    ];
    final targetColumns = columns
        .where((c) => selectSources.containsKey(c.name))
        .toList();

    // Dropping a referenced table increments SQLite's *deferred* foreign key
    // violation counter; re-inserting the parent rows into the recreated
    // table decrements it again, so the sequence below is valid both inside
    // an outer transaction and on its own (the savepoint acts as BEGIN).
    final backup = '__daravel_backup_$table';
    await _executor.execute('SAVEPOINT daravel_rebuild');
    try {
      await _executor.execute('PRAGMA defer_foreign_keys = ON');
      await _executor.execute(
        'CREATE TABLE ${grammar.wrap(backup)} AS SELECT * FROM ${grammar.wrap(table)}',
      );
      await _executor.execute('DROP TABLE ${grammar.wrap(table)}');
      await _executor.execute(
        'CREATE TABLE ${grammar.wrap(table)} (${definition.join(', ')})',
      );
      if (targetColumns.isNotEmpty) {
        await _executor.execute(
          'INSERT INTO ${grammar.wrap(table)} (${targetColumns.map((c) => grammar.wrap(c.name)).join(', ')}) '
          'SELECT ${targetColumns.map((c) => grammar.wrap(selectSources[c.name]!)).join(', ')} FROM ${grammar.wrap(backup)}',
        );
      }
      await _executor.execute('DROP TABLE ${grammar.wrap(backup)}');
      for (final index in indexes.where((i) => !i.auto)) {
        await _executor.execute(
          'CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${grammar.wrap(index.name)} ON '
          '${grammar.wrap(table)} (${index.columns.map(grammar.wrap).join(', ')})',
        );
      }
      await _executor.execute('RELEASE SAVEPOINT daravel_rebuild');
    } catch (_) {
      await _executor.execute('ROLLBACK TO SAVEPOINT daravel_rebuild');
      await _executor.execute('RELEASE SAVEPOINT daravel_rebuild');
      rethrow;
    }
  }

  static void _replace(List<String> list, String from, String to) {
    for (var i = 0; i < list.length; i++) {
      if (list[i] == from) {
        list[i] = to;
      }
    }
  }

  _ExistingColumn _fromDefinition(ColumnDefinition column) => _ExistingColumn(
    name: column.name,
    type:
        grammar.typeFor(column) +
        (column.type == .enumeration
            ? ' CHECK (${grammar.wrap(column.name)} IN (${column.allowed.map(grammar.literal).join(', ')}))'
            : ''),
    notNull: !column.isNullable && !column.isAutoIncrement,
    defaultSql: column.hasDefault
        ? grammar.defaultClause(column).replaceFirst(' DEFAULT ', '')
        : null,
    primaryKey: column.isPrimary || column.isAutoIncrement,
    autoIncrement: column.isAutoIncrement,
  );

  String _compileExisting(_ExistingColumn column) {
    final buffer = StringBuffer()
      ..write(grammar.wrap(column.name))
      ..write(' ')
      ..write(column.type);
    if (column.primaryKey) {
      buffer.write(' PRIMARY KEY');
      if (column.autoIncrement) {
        buffer.write(' AUTOINCREMENT');
      }
    }
    if (column.notNull) {
      buffer.write(' NOT NULL');
    }
    if (column.defaultSql != null) {
      buffer.write(' DEFAULT ${column.defaultSql}');
    }
    return buffer.toString();
  }

  Future<List<_ExistingColumn>> _columns(String table) async {
    final rows = await _executor.select(
      'PRAGMA table_info(${grammar.wrap(table)})',
    );
    if (rows.isEmpty) {
      throw StateError('Table [$table] does not exist.');
    }
    final sqlRows = await _executor.select(
      "SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?",
      [table],
    );
    final createSql = sqlRows.isEmpty
        ? ''
        : '${sqlRows.first['sql']}'.toUpperCase();
    return [
      for (final row in rows)
        _ExistingColumn(
          name: row['name'] as String,
          type: row['type'] as String,
          notNull: row['notnull'] == 1,
          defaultSql: row['dflt_value'] as String?,
          primaryKey: row['pk'] != 0,
          autoIncrement: row['pk'] != 0 && createSql.contains('AUTOINCREMENT'),
        ),
    ];
  }

  Future<List<_ExistingIndex>> _indexes(String table) async {
    final rows = await _executor.select(
      'PRAGMA index_list(${grammar.wrap(table)})',
    );
    final result = <_ExistingIndex>[];
    for (final row in rows) {
      final name = row['name'] as String;
      final origin = '${row['origin']}';
      if (origin == 'pk') {
        continue;
      }
      final columns = await _executor.select(
        'PRAGMA index_info(${grammar.wrap(name)})',
      );
      result.add(
        _ExistingIndex(
          name: name,
          unique: row['unique'] == 1,
          columns: [for (final c in columns) c['name'] as String],
          auto: origin == 'u' || name.startsWith('sqlite_autoindex'),
        ),
      );
    }
    return result;
  }

  Future<List<_ExistingForeignKey>> _foreignKeys(String table) async {
    final rows = await _executor.select(
      'PRAGMA foreign_key_list(${grammar.wrap(table)})',
    );
    final grouped = <Object?, _ExistingForeignKey>{};
    for (final row in rows) {
      final key = grouped.putIfAbsent(
        row['id'],
        () => _ExistingForeignKey(
          table: row['table'] as String,
          from: [],
          to: [],
          onDelete: '${row['on_delete']}',
          onUpdate: '${row['on_update']}',
        ),
      );
      key.from.add(row['from'] as String);
      key.to.add(row['to'] as String);
    }
    return grouped.values.toList();
  }
}
