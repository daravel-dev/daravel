/// A column of the model [M] whose values are [V], as `dartisan model:sync`
/// writes them into the model's `cols` record:
///
/// ```dart
/// static const cols = (
///   id: ModelColumn<User, int>('id'),
///   email: ModelColumn<User, String>('email'),
///   age: ModelColumn<User, int?>('age'),
/// );
///
/// await User.query()
///     .where(User.cols.age.gte(18))
///     .where(User.cols.email.endsWith('@example.com'))
///     .orderByDesc(User.cols.id)
///     .pluck(User.cols.email);
/// ```
///
/// Typing `User.cols.` lists the columns, and a misspelt one does not
/// compile; typing `User.cols.age.` lists the conditions, whose value must
/// be of the column's type. At run time the token is its [name], a plain
/// `String`, so the SQL is exactly the one the string gives, at no cost.
///
/// It is deliberately not a `String` to the compiler: the editor then shows
/// only [name] and the conditions after `User.cols.email.`, not the forty
/// members of `String`, and a `String` method can never be called by
/// mistake where a condition was meant. Query builder methods that take a
/// column accept it (`where`, `orderBy`, `select`, `pluck`, `latest`, ...);
/// elsewhere write [name] (and on a model
/// `user.increment(User.cols.views.name)`).
extension type const ModelColumn<M extends Model, V>._(String name)
    implements Object {
  /// The column named [name]; generated by `dartisan model:sync`.
  const ModelColumn(String name) : this._(name);

  /// `column = value`, or `column IS NULL` when [value] is null.
  ColumnPredicate<M> eq(V value) =>
      ColumnPredicate._(QueryBuilder.whereClause(name, '=', value));

  /// `column <> value`, or `column IS NOT NULL` when [value] is null.
  ColumnPredicate<M> neq(V value) =>
      ColumnPredicate._(QueryBuilder.whereClause(name, '<>', value));

  /// `column IN (...)`; an empty list matches nothing, as `whereIn`.
  ColumnPredicate<M> inValues(Iterable<V> values) =>
      ColumnPredicate._(InWhere(name, List<Object?>.of(values)));

  /// `column NOT IN (...)`; an empty list matches everything.
  ColumnPredicate<M> notInValues(Iterable<V> values) =>
      ColumnPredicate._(InWhere(name, List<Object?>.of(values), not: true));
}

/// A condition on a typed column of [M] (`User.cols.age.gte(18)`), for
/// `where` and `orWhere`. It is the query's condition node itself: no
/// object beyond the one `where(column, operator, value)` makes.
extension type const ColumnPredicate<M extends Model>._(WhereClause clause)
    implements Object {}

/// `IS NULL` and `IS NOT NULL`, on any column.
extension NullableColumnConditions<M extends Model, V extends Object>
    on ModelColumn<M, V?> {
  /// `column IS NULL`.
  ColumnPredicate<M> isNull() => ColumnPredicate._(NullWhere(name));

  /// `column IS NOT NULL`.
  ColumnPredicate<M> isNotNull() =>
      ColumnPredicate._(NullWhere(name, not: true));
}

/// Comparisons, on columns whose values compare (numbers, strings, dates).
/// The bound is never null, also on a nullable column.
extension ComparableColumnConditions<
  M extends Model,
  V extends Comparable<Object>
>
    on ModelColumn<M, V?> {
  /// `column > value`.
  ColumnPredicate<M> gt(V value) =>
      ColumnPredicate._(QueryBuilder.whereClause(name, '>', value));

  /// `column >= value`.
  ColumnPredicate<M> gte(V value) =>
      ColumnPredicate._(QueryBuilder.whereClause(name, '>=', value));

  /// `column < value`.
  ColumnPredicate<M> lt(V value) =>
      ColumnPredicate._(QueryBuilder.whereClause(name, '<', value));

  /// `column <= value`.
  ColumnPredicate<M> lte(V value) =>
      ColumnPredicate._(QueryBuilder.whereClause(name, '<=', value));

  /// `column BETWEEN min AND max`, inclusive.
  ColumnPredicate<M> between(V min, V max) =>
      ColumnPredicate._(BetweenWhere(name, min, max));

  /// `column NOT BETWEEN min AND max`.
  ColumnPredicate<M> notBetween(V min, V max) =>
      ColumnPredicate._(BetweenWhere(name, min, max, not: true));
}

/// Pattern conditions, on text columns.
extension TextColumnConditions<M extends Model> on ModelColumn<M, String?> {
  /// `column LIKE pattern`, with `%` and `_` as wildcards: the same as
  /// `where(column, 'like', pattern)`, so case sensitivity is the
  /// database's (`whereLike` is the case-insensitive form).
  ColumnPredicate<M> like(String pattern) =>
      ColumnPredicate._(QueryBuilder.whereClause(name, 'LIKE', pattern));

  /// The text starts with [prefix], taken literally (`%` and `_` in it
  /// match only themselves).
  ColumnPredicate<M> startsWith(String prefix) =>
      _escaped('${BasicWhere.escapeLike(prefix)}%');

  /// The text ends with [suffix], taken literally.
  ColumnPredicate<M> endsWith(String suffix) =>
      _escaped('%${BasicWhere.escapeLike(suffix)}');

  /// The text contains [part], taken literally.
  ColumnPredicate<M> contains(String part) =>
      _escaped('%${BasicWhere.escapeLike(part)}%');

  ColumnPredicate<M> _escaped(String pattern) => ColumnPredicate._(
    QueryBuilder.whereClause(name, 'LIKE', pattern, escaped: true),
  );
}

/// A relation of the model [P] to models [C], as `dartisan model:sync`
/// writes them into the model's `rels` record:
///
/// ```dart
/// static const rels = (posts: RelationToken<User, Post>('posts'));
///
/// await User.query()
///     .with_([User.rels.posts.nested(Post.rels.comments)])
///     .whereHas(User.rels.posts)
///     .get();
/// ```
///
/// Typing `User.rels.` lists the relations; a misspelt one, a chain that
/// does not follow the models, or a column of another model in [only] does
/// not compile. At run time the token is its [name], a plain `String`, so
/// `with_`, `withCount`, `whereHas`, `load` and the others see the string
/// they always saw.
///
/// A path goes on with the relations of [C] as getters, which `model:sync`
/// writes next to each model (`<Model>RelationPath`):
/// `User.rels.posts.comments.author` is `posts.comments.author`, checked at
/// every step, and typing `User.rels.posts.` lists the relations of `Post`.
/// The getters of a model are in its file, so the file using the path
/// imports it (or the models barrel, `lib/app/models/models.dart`). A
/// relation named like a member of this type ([relationTokenMembers]) has
/// no getter, since the member would always win; `nested` reaches it, as it
/// reaches any relation. After a `MorphTo` relation, whose model is only
/// known at run time, the path stops; `nested` or a string goes on.
extension type const RelationToken<P extends Model, C extends Model>._(
  String name,
) implements Object {
  /// The relation named [name]; generated by `dartisan model:sync`.
  const RelationToken(String name) : this._(name);

  /// This relation followed by [next], a relation of [C]:
  /// `User.rels.posts.nested(Post.rels.comments)` is `posts.comments`.
  RelationToken<P, G> nested<G extends Model>(RelationToken<C, G> next) =>
      RelationToken<P, G>._('$name.${next.name}');

  /// This relation, eager loaded with only [columns] of [C]:
  /// `User.rels.posts.only([Post.cols.id, Post.cols.title])` is
  /// `posts:id,title`, for `with_`. The key the relation matches on (the
  /// foreign key of `HasMany`, the owner key of `BelongsTo`, ...) is added
  /// when left out, so the relation is never empty for lack of it; Laravel
  /// asks for it to be listed.
  RelationColumns<P> only(List<ModelColumn<C, Object?>> columns) =>
      RelationColumns<P>._(
        '$name:${[for (final column in columns) column.name].join(',')}',
      );
}

/// The names a relation path getter cannot have: the members of
/// [RelationToken], its own and those of `Object`. A member always wins
/// over an extension getter of the same name, without an error, so
/// `User.rels.posts.name` would be the token's text, never a relation
/// named `name`. `dartisan model:sync` writes no getter for such a
/// relation and says so; `nested(Post.rels.name)` reaches it.
///
/// A test keeps this set equal to the members [RelationToken] declares.
const Set<String> relationTokenMembers = {
  'name',
  'nested',
  'only',
  'hashCode',
  'runtimeType',
  'toString',
  'noSuchMethod',
};

/// A relation of [P] with the columns to load (`posts:id,title`), made by
/// [RelationToken.only] for `with_`.
extension type const RelationColumns<P extends Model>._(String spec)
    implements Object {}
