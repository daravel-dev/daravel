import 'dart:io';

import 'package:analyzer/dart/analysis/utilities.dart';
import 'package:analyzer/dart/ast/token.dart';
import 'package:daravel/daravel.dart';
import 'package:dartisan_cli/dartisan_cli.dart';
import 'package:test/test.dart';
import 'package:yaml/yaml.dart';

/// Text from the application (a route's summary, a model's description,
/// the application's name) stays text in the generated client: in a `///`
/// comment on one line, in `pubspec.yaml` one quoted value, whatever line
/// breaks, quotes or `$` it holds.
void main() {
  const summary = 'List items\n}\nvoid injectedTopLevel() {}\nclass EvilFake {';
  const description = 'Item model\r\n*/\nvoid injectedModelFn() {}\n//';
  const title =
      'Demo\nvoid injectedTitleFn() {}\ndependency_overrides:\n'
      '  http:\n    path: ../evil "\$x" \\';

  late GeneratedClient client;

  setUpAll(() async {
    final app = Application.configure(basePath: Directory.systemTemp.path)
        .withEnv(const {'APP_ENV': 'testing', 'DB_DATABASE': ':memory:'})
        .withRouting(
          api: (r) => r
              .get('/items', (_) => const <Object?>[])
              .name('items.index')
              .summary(summary)
              .returns(const {
                'type': 'object',
                'description': description,
                'properties': {
                  'id': {'type': 'integer'},
                },
              }, name: 'Item'),
        )
        .create();
    await app.boot();
    addTearDown(app.shutdown);
    client = generateClient(
      routesUnder(app.router.routes, '/api'),
      packageName: 'demo_client',
      baseUrl: 'http://127.0.0.1:8000',
      title: title,
      states: clientStates.toSet(),
    );
  });

  test('every generated Dart file parses, with no injected declaration', () {
    final dart = client.files.entries.where((e) => e.key.endsWith('.dart'));
    expect(dart, isNotEmpty);
    for (final MapEntry(key: path, value: source) in dart) {
      final result = parseString(content: source, throwIfDiagnostics: false);
      expect(result.errors, isEmpty, reason: path);
      // Code tokens only: comments are not tokens.
      final names = <String>{};
      for (
        Token? token = result.unit.beginToken;
        token != null && !token.isEof;
        token = token.next
      ) {
        names.add(token.lexeme);
      }
      for (final injected in [
        'injectedTopLevel',
        'EvilFake',
        'injectedModelFn',
        'injectedTitleFn',
      ]) {
        expect(names, isNot(contains(injected)), reason: '$path: $injected');
      }
    }
    // The text is still there, on one line of a comment.
    expect(
      client.files['lib/src/api.dart'],
      contains('/// List items } void injectedTopLevel() {} class EvilFake {'),
    );
    expect(
      client.files['lib/src/models.dart'],
      contains('/// Item model */ void injectedModelFn() {} //'),
    );
  });

  test('pubspec.yaml parses to the same keys, the title inside the '
      'description', () {
    final yaml = loadYaml(client.files['pubspec.yaml']!) as YamlMap;
    expect(yaml.keys, isNot(contains('dependency_overrides')));
    expect(yaml['name'], 'demo_client');
    expect(
      yaml['description'],
      'Typed client of Demo void injectedTitleFn() {} dependency_overrides: '
      'http: path: ../evil "\$x" \\, generated by dartisan client:flutter.',
    );
  });
}
