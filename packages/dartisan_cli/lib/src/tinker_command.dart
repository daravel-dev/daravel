import 'dart:io';

import 'package:args/command_runner.dart';
import 'package:path/path.dart' as p;

import 'generator.dart';
import 'project_commands.dart';

/// `tinker "<expression>"` — evaluates a Dart expression inside the booted
/// application and prints the result (models and collections as JSON):
///
/// ```bash
/// dartisan tinker "await User.query().where('active', true).count()"
/// dartisan tinker "await Hash.make('secret')"
/// ```
///
/// Dart has no `eval`, so the expression is written into a small program
/// (`.dart_tool/daravel/tinker.dart`) that imports the application and its
/// models, and that program is run with `dart run`. It is one-shot: each
/// call boots the application again.
final class TinkerCommand extends Command<int> {
  TinkerCommand({this.root});

  /// Project root; located from the working directory when `null`.
  final String? root;

  @override
  String get name => 'tinker';

  @override
  String get description =>
      'Evaluate a Dart expression in the booted application.';

  @override
  String get invocation => 'dartisan tinker "<expression>"';

  @override
  Future<int> run() async {
    final expression = argResults!.rest.join(' ').trim();
    if (expression.isEmpty) {
      usageException(
        'Pass a Dart expression, e.g. "await User.query().count()".',
      );
    }
    final paths = ProjectPaths.locate(root);
    final models = Directory(p.join(paths.root, 'lib', 'app', 'models'));
    final imports = [
      if (models.existsSync())
        for (final file in models.listSync().whereType<File>())
          if (file.path.endsWith('.dart'))
            'package:${paths.packageName}/app/models/${p.basename(file.path)}',
    ]..sort();
    final script =
        File(p.join(paths.root, '.dart_tool', 'daravel', 'tinker.dart'))
          ..parent.createSync(recursive: true)
          ..writeAsStringSync(renderTinkerScript(imports, expression));
    final process = await Process.start(
      dartExecutable(),
      ['run', script.path],
      workingDirectory: paths.root,
      mode: ProcessStartMode.inheritStdio,
    );
    return process.exitCode;
  }
}

/// The program `tinker` runs for [expression], importing [imports].
String renderTinkerScript(List<String> imports, String expression) {
  final buffer = StringBuffer()
    ..writeln('// Generated by `dartisan tinker`; safe to delete.')
    ..writeln("import 'dart:convert';")
    ..writeln()
    ..writeln("import 'package:daravel/daravel.dart';")
    ..writeln();
  for (final import in imports) {
    buffer.writeln("import '$import';");
  }
  buffer
    ..writeln("import '../../bootstrap/app.dart';")
    ..writeln()
    ..writeln('Future<void> main() async {')
    ..writeln('  final app = createApp();')
    ..writeln('  await app.boot();')
    ..writeln('  try {')
    ..writeln('    final Object? result = await app.run<Object?>(')
    ..writeln('      () async => $expression,')
    ..writeln('    );')
    ..writeln('    print(')
    ..writeln('      result is String')
    ..writeln('          ? result')
    ..writeln("          : JsonEncoder.withIndent('  ', (Object? value) {")
    ..writeln('              return value is JsonSerializable')
    ..writeln('                  ? value.toJson()')
    ..writeln("                  : '\$value';")
    ..writeln('            }).convert(result),')
    ..writeln('    );')
    ..writeln('  } finally {')
    ..writeln('    await app.shutdown();')
    ..writeln('  }')
    ..writeln('}');
  return buffer.toString();
}
