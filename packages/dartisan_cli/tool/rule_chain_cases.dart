Future<void> main(List<String> args) async {
  final out = File('test/rule_chain_equivalence_test.dart');
  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/rule_chain_cases.dart. Do not edit.')
    ..writeln('//')
    ..writeln(
      '// What a string rule list means (RuleParser) against what the chain',
    )
    ..writeln("// the editor's fix writes for it means, rule by rule (W9.8).")
    ..writeln("import 'package:daravel/daravel.dart';")
    ..writeln("import 'package:daravel_lints/daravel_lints.dart';")
    ..writeln("import 'package:test/test.dart';")
    ..writeln()
    ..writeln("import 'rule_chain_equivalence.dart';")
    ..writeln()
    ..writeln('void main() {')
    ..writeln('  final cases = <(String, String, Object)>[');
  for (final dsl in convertible) {
    final chain = ruleChainSource(dsl);
    if (chain == null) {
      stderr.writeln('No chain for "$dsl"');
      exitCode = 1;
      return;
    }
    buffer.writeln('    (${_literal(dsl)}, ${_literal(chain)}, $chain),');
  }
  buffer
    ..writeln('  ];')
    ..writeln()
    ..writeln('  for (final (dsl, source, chain) in cases) {')
    ..writeln("    test('\"\$dsl\" is \$source', () async {")
    ..writeln('      expect(ruleChainSource(dsl), source);')
    ..writeln('      await expectSameRules(dsl, RuleParser.parseValue(chain));')
    ..writeln('    });')
    ..writeln('  }')
    ..writeln()
    ..writeln("  test('no chain where none keeps the meaning', () {")
    ..writeln('    for (final dsl in <String>[');
  for (final dsl in notConvertible) {
    buffer.writeln('      ${_literal(dsl)},');
  }
  buffer
    ..writeln('    ]) {')
    ..writeln('      expect(ruleChainSource(dsl), isNull, reason: dsl);')
    ..writeln('    }')
    ..writeln('  });')
    ..writeln('}');
  final formatted = await _format(buffer.toString());
  if (args.contains('--check')) {
    final current = out.existsSync() ? out.readAsStringSync() : '';
    if (current != formatted) {
      stderr.writeln(
        '${out.path} is out of date: run tool/rule_chain_cases.dart',
      );
      exitCode = 1;
    }
    return;
  }
  out.writeAsStringSync(formatted);
  stdout.writeln('Wrote ${out.path}');
}

String _literal(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$');
  return "'$escaped'";
}

/// Formats [source] with `dart format`, as the CI gate would.
Future<String> _format(String source) async {
  final temp = Directory.systemTemp.createTempSync('rule_chain_cases');
  try {
    final file = File('${temp.path}/cases.dart')..writeAsStringSync(source);
    final result = await Process.run(Platform.resolvedExecutable, [
      'format',
      file.path,
    ]);
    if (result.exitCode != 0) {
      throw StateError('dart format failed: ${result.stderr}');
    }
    return file.readAsStringSync();
  } finally {
    temp.deleteSync(recursive: true);
  }
}
